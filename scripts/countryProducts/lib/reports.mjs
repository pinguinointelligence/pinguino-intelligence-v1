function cellState(selection) {
  if (selection.selectionState === 'SELECTION_CLOSED') {
    switch (selection.route.decision) {
      case 'ROUTE_ALREADY_PRESENT':
        return 'closed · route present';
      case 'ROUTE_CREATABLE_NOW':
        return 'closed · route now';
      default: {
        if (selection.route.blockers.includes('MARKET_NOT_IN_CATALOG_MARKET_COUNTRIES')) return 'closed · FK';
        if (selection.route.blockers.some((b) => b.startsWith('EXISTING_PRIMARY'))) return 'closed · conflict';
        const status = selection.route.blockers.find((b) => b.startsWith(WORKBOOK_STATUS_BLOCKER));
        return status ? `closed · ${status.slice(WORKBOOK_STATUS_BLOCKER.length)}` : 'closed · blocked';
      }
    }
  }
  return `${selection.selectionState === 'BLOCKED' ? 'blocked' : 'open'} ${selection.openGapId}`;
}

