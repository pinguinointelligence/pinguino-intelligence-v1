function statusBySlotTable(registry) {
  const bySlot = registry.counts.workbookStatusBySlot ?? {};
  const statuses = [...new Set(Object.values(bySlot).flatMap((entry) => Object.keys(entry)))].sort(compare);
  return table(
    ['Slot (workbook role)', ...statuses, 'Total'],
    Object.entries(bySlot).map(([slot, entry]) => [
      slot === 'STABILIZER' ? 'STABILIZER (TARA)' : slot,
      ...statuses.map((status) => entry[status] ?? 0),
      Object.values(entry).reduce((sum, value) => sum + value, 0),
    ]),
  );
}

function stabilizerStatementV23(registry) {
  const byProduct = new Map();
  for (const selection of registry.selections.filter((entry) => entry.slot === 'STABILIZER')) {
    byProduct.set(selection.productKey, [...(byProduct.get(selection.productKey) ?? []), selection.country]);
  }
  const parts = [...byProduct.entries()]
    .sort((a, b) => b[1].length - a[1].length || compare(a[0], b[0]))
    .map(([productKey, countries]) => {
      const product = registry.products.find((entry) => entry.productKey === productKey);
      return `${product?.exactName ?? productKey} (${product?.brand ?? '—'}) in ${countries.length === 1 ? countries[0] : `${countries.length} countries`}`;
    });
  return `**STABILIZER slot (workbook role TARA).** v23 closes all ${registry.selections.filter((entry) => entry.slot === 'STABILIZER').length} STABILIZER selections: ${parts.join('; ')}. TARA stays one functional STABILIZER option, not a mandatory ingredient; a non-TARA stabilizer would need its own PR identity, composition, Engine readiness and recalculated grams.`;
}

