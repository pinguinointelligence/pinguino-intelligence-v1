const REPORT_PROFILES = Object.freeze({ GELATO_BASE_V12: V12_REPORT, GELATO_BASE_V23: V23_REPORT });

function reportProfileFor(registry) {
  const registryId = String(registry.registryId);
  if (!Object.hasOwn(REPORT_PROFILES, registryId)) throw new Error(`No report profile for registry ${registryId}.`);
  return REPORT_PROFILES[registryId];
}

