import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { gzipSync } from 'node:zlib';

const root = process.cwd();
const releasePath = resolve(root, 'public/mapper-search-runtime/sa10-final-frozen.json');
const outputPath = resolve(
  root,
  'supabase/functions/_shared/generated/productSemanticSearch.bundle.mjs',
);
const releaseBytes = readFileSync(releasePath);
const release = JSON.parse(releaseBytes.toString('utf8'));
const sha256 = createHash('sha256').update(releaseBytes).digest('hex');
if (sha256 !== '20e92e6c84d8909e97bde2359d81a0aa429b3f0c6311474c3e50b10705936127') {
  throw new Error(`Unexpected FINAL Search release hash: ${sha256}`);
}
if (release.releaseId !== 'GELLATTI-SA10-2026-09-10-FINAL') {
  throw new Error(`Unexpected FINAL Search release id: ${release.releaseId}`);
}

const payload = gzipSync(releaseBytes, { level: 9 }).toString('base64');
const source = `/** GENERATED by scripts/buildProductSemanticSearchEdgeBundle.mjs. */
import { createMapperSearchRuntime } from '../../../../src/features/mapper-search-runtime/runtime.ts';
import { normalizeMapperSearchText } from '../../../../src/features/mapper-search-runtime/normalize.ts';

export const PRODUCT_SEMANTIC_SEARCH_RELEASE_ID = ${JSON.stringify(release.releaseId)};
export const PRODUCT_SEMANTIC_SEARCH_RELEASE_SHA256 = ${JSON.stringify(sha256)};
const COMPRESSED_RELEASE_BASE64 = ${JSON.stringify(payload)};
const NO_TELEMETRY = { record: () => undefined };
let hydrated = null;

const localeKey = (value) => {
  const normalized = String(value ?? 'en').replace('_', '-');
  const lower = normalized.toLowerCase();
  if (lower === 'zh-cn' || lower === 'zh-sg' || lower === 'zh-hans') return 'zh-Hans';
  if (lower === 'zh-tw' || lower === 'zh-hk' || lower === 'zh-hant') return 'zh-Hant';
  return normalized.split('-')[0]?.toLowerCase() || 'en';
};

async function hydrate() {
  if (hydrated) return hydrated;
  hydrated = (async () => {
    const compressed = Uint8Array.from(atob(COMPRESSED_RELEASE_BASE64), (value) => value.charCodeAt(0));
    const stream = new Blob([compressed]).stream().pipeThrough(new DecompressionStream('gzip'));
    const release = JSON.parse(await new Response(stream).text());
    const runtime = createMapperSearchRuntime(release);
    const localeByMarket = new Map(release.marketRoutes.flatMap((route) => {
      const market = String(route.ISO2 ?? '').trim().toUpperCase();
      const locale = String(route['Proponowane słowniki'] ?? '').split(/[;,\\s]+/u)[0]?.trim();
      return market && locale ? [[market, locale]] : [];
    }));
    const localeHints = release.searchAliases
      .map((alias) => ({ locale: localeKey(alias.locale), surface: alias.normalized }))
      .filter((hint) => hint.surface.length >= 4)
      .sort((left, right) => right.surface.length - left.surface.length);
    return { runtime, localeByMarket, localeHints };
  })();
  return hydrated;
}

export async function resolveFinalProductSemanticSearch(query, marketCountries = []) {
  const { runtime, localeByMarket, localeHints } = await hydrate();
  const market = marketCountries
    .map((country) => String(country).trim().toUpperCase())
    .find((country) => localeByMarket.has(country)) ?? 'GLOBAL';
  const normalized = normalizeMapperSearchText(query, 'en');
  let longest = 0;
  let detected = null;
  let conflict = false;
  for (const hint of localeHints) {
    if (hint.surface.length < longest) break;
    if (!normalized.includes(normalizeMapperSearchText(hint.surface, 'en'))) continue;
    if (hint.surface.length > longest) {
      longest = hint.surface.length;
      detected = hint.locale;
      conflict = false;
    } else if (detected !== hint.locale) {
      conflict = true;
    }
  }
  const locale = localeByMarket.get(market) ?? (conflict ? null : detected) ?? 'en';
  return runtime.resolve(query, {
    localeVariant: locale,
    marketScope: market,
    telemetry: NO_TELEMETRY,
  });
}
`;

writeFileSync(outputPath, source);
console.log(
  `product semantic search edge bundle: ${release.releaseId}, ${releaseBytes.length} -> ${payload.length} base64 bytes`,
);
