import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { gzipSync } from 'node:zlib';

const root = process.cwd();
const releasePath = resolve(root, 'public/mapper-search-runtime/sa10-final-frozen.json');
const outputPath = resolve(
  root,
  'supabase/functions/_shared/generated/productSemanticSearch.bundle.mjs',
);
const releaseBytes = readFileSync(releasePath);
const release = JSON.parse(releaseBytes.toString('utf8'));
const sha256 = createHash('sha256').update(releaseBytes).digest('hex');
if (sha256 !== '20e92e6c84d8909e97bde2359d81a0aa429b3f0c6311474c3e50b10705936127') {
  throw new Error(`Unexpected FINAL Search release hash: ${sha256}`);
}
if (release.releaseId !== 'GELLATTI-SA10-2026-09-10-FINAL') {
  throw new Error(`Unexpected FINAL Search release id: ${release.releaseId}`);
}

const localeKey = (value) => {
  const normalized = String(value ?? 'en').replace('_', '-');
  const lower = normalized.toLowerCase();
  if (lower === 'zh-cn' || lower === 'zh-sg' || lower === 'zh-hans') return 'zh-Hans';
  if (lower === 'zh-tw' || lower === 'zh-hk' || lower === 'zh-hant') return 'zh-Hant';
  return normalized.split('-')[0]?.toLowerCase() || 'en';
};

const gzipJson = (value) =>
  gzipSync(Buffer.from(JSON.stringify(value)), { level: 9 }).toString('base64');
const localeSegments = new Map();
const putSegmentRow = (kind, row) => {
  const key = localeKey(row.locale);
  const segment = localeSegments.get(key) ?? { searchAliases: [], roleAliases: [] };
  segment[kind].push(row);
  localeSegments.set(key, segment);
};
release.searchAliases.forEach((row) => putSegmentRow('searchAliases', row));
release.roleAliases.forEach((row) => putSegmentRow('roleAliases', row));

const commonProjection = {
  schemaVersion: release.schemaVersion,
  releaseId: release.releaseId,
  technicalAliases: release.technicalAliases,
  localeContracts: release.localeContracts,
  marketRoutes: release.marketRoutes,
  precedence: release.precedence,
  runtimeLexicon: release.runtimeLexicon,
  roleGrammar: release.roleGrammar,
};
const aliasHintRows = (alias, detectorEligible) => {
  const concept =
    alias.targetType === 'INGREDIENT_CONCEPT' || alias.targetType === 'NAMED_COMPOSITE';
  const surfaces = new Map();
  if (alias.normalized) surfaces.set(alias.normalized, detectorEligible ? 1 : 0);
  if (alias.fallback && !surfaces.has(alias.fallback)) surfaces.set(alias.fallback, 0);
  return [...surfaces].map(([surface, detectLocale]) => [
    localeKey(alias.locale),
    surface,
    concept ? 1 : 0,
    detectLocale,
  ]);
};
const runtimeLexiconSearch = Array.isArray(release.runtimeLexicon?.search)
  ? release.runtimeLexicon.search
  : [];
const localeHints = [
  ...release.searchAliases.flatMap((alias) => aliasHintRows(alias, true)),
  ...runtimeLexiconSearch.flatMap((alias) => aliasHintRows(alias, false)),
];
const compressedSegments = Object.fromEntries(
  [...localeSegments.entries()].map(([key, value]) => [key, gzipJson(value)]),
);
const commonPayload = gzipJson(commonProjection);
const hintsPayload = gzipJson(localeHints);

const source = `/** GENERATED by scripts/buildProductSemanticSearchEdgeBundle.mjs. */
import { createMapperSearchRuntime } from '../../../../src/features/mapper-search-runtime/runtime.ts';
import { normalizeMapperSearchText } from '../../../../src/features/mapper-search-runtime/normalize.ts';

export const PRODUCT_SEMANTIC_SEARCH_RELEASE_ID = ${JSON.stringify(release.releaseId)};
export const PRODUCT_SEMANTIC_SEARCH_RELEASE_SHA256 = ${JSON.stringify(sha256)};
const COMPRESSED_COMMON_BASE64 = ${JSON.stringify(commonPayload)};
const COMPRESSED_LOCALE_HINTS_BASE64 = ${JSON.stringify(hintsPayload)};
const COMPRESSED_LOCALE_SEGMENTS_BASE64 = Object.freeze(${JSON.stringify(compressedSegments)});
const NO_TELEMETRY = { record: () => undefined };
let hydratedCommon = null;
let hydratedHints = null;
let hydratedWildcard = null;

const localeKey = (value) => {
  const normalized = String(value ?? 'en').replace('_', '-');
  const lower = normalized.toLowerCase();
  if (lower === 'zh-cn' || lower === 'zh-sg' || lower === 'zh-hans') return 'zh-Hans';
  if (lower === 'zh-tw' || lower === 'zh-hk' || lower === 'zh-hant') return 'zh-Hant';
  return normalized.split('-')[0]?.toLowerCase() || 'en';
};

async function decompressJson(encoded) {
  const compressed = Uint8Array.from(atob(encoded), (value) => value.charCodeAt(0));
  const stream = new Blob([compressed]).stream().pipeThrough(new DecompressionStream('gzip'));
  return JSON.parse(await new Response(stream).text());
}

async function hydrateCommon() {
  hydratedCommon ??= decompressJson(COMPRESSED_COMMON_BASE64);
  return hydratedCommon;
}

async function hydrateHints() {
  hydratedHints ??= decompressJson(COMPRESSED_LOCALE_HINTS_BASE64);
  return hydratedHints;
}

async function hydrateSegment(locale) {
  const key = localeKey(locale);
  const encoded = COMPRESSED_LOCALE_SEGMENTS_BASE64[key];
  return encoded ? decompressJson(encoded) : { searchAliases: [], roleAliases: [] };
}

async function hydrateWildcard() {
  hydratedWildcard ??= hydrateSegment('*');
  return hydratedWildcard;
}

async function runtimeForLocale(locale) {
  const [common, segment, wildcard] = await Promise.all([
    hydrateCommon(),
    hydrateSegment(locale),
    hydrateWildcard(),
  ]);
  const searchAliases = [...wildcard.searchAliases, ...segment.searchAliases];
  const roleAliases = [...wildcard.roleAliases, ...segment.roleAliases];
  return createMapperSearchRuntime({
    ...common,
    searchAliases,
    roleAliases,
    dataContracts: [],
    mapperRows: [],
    counts: {
      mapper: 0,
      mapperColumns: 0,
      searchAliases: searchAliases.length,
      roleAliases: roleAliases.length,
      technicalAliases: common.technicalAliases.length,
      concepts: 0,
      localeContracts: common.localeContracts.length,
      markets: common.marketRoutes.length,
      dataContracts: 0,
    },
  });
}

const semanticConceptSignature = (resolution) => [
  ...new Set(resolution.searchMentions.flatMap((mention) => {
    if (mention.targetType !== 'INGREDIENT_CONCEPT' && mention.targetType !== 'NAMED_COMPOSITE') {
      return [];
    }
    return [\`${'${mention.targetType}'}:${'${mention.specializationId ?? mention.targetId}'}\`];
  })),
].sort().join('|');

const carriesAmbiguityGate = (resolution) =>
  resolution.technicalMentions.some((mention) => mention.action === 'AMBIGUITY_GATE') ||
  resolution.searchGaps.some((gap) =>
    gap.reason === 'AMBIGUOUS_FALLBACK' || gap.reason === 'AMBIGUOUS_TECHNICAL_CODE'
  );

export async function resolveFinalProductSemanticSearch(query, marketCountries = []) {
  const [common, localeHints] = await Promise.all([hydrateCommon(), hydrateHints()]);
  const localeByMarket = new Map(common.marketRoutes.flatMap((route) => {
    const market = String(route.ISO2 ?? '').trim().toUpperCase();
    const locale = String(route['Proponowane słowniki'] ?? '').split(/[;,\\s]+/u)[0]?.trim();
    return market && locale ? [[market, locale]] : [];
  }));
  const market = marketCountries
    .map((country) => String(country).trim().toUpperCase())
    .find((country) => localeByMarket.has(country)) ?? 'GLOBAL';
  const normalized = normalizeMapperSearchText(query, 'en');
  let longest = 0;
  let detected = null;
  let conflict = false;
  const conceptCandidateLocales = new Set();
  const normalizedQueriesByLocale = new Map([['en', normalized]]);
  for (const [hintLocale, surface, isConcept, detectLocale] of localeHints) {
    const candidateLocale = localeKey(hintLocale);
    const normalizedSurface = normalizeMapperSearchText(surface, candidateLocale);
    const localeQuery = normalizedQueriesByLocale.get(candidateLocale) ??
      normalizeMapperSearchText(query, candidateLocale);
    normalizedQueriesByLocale.set(candidateLocale, localeQuery);
    if (isConcept && normalizedSurface && localeQuery.includes(normalizedSurface)) {
      conceptCandidateLocales.add(candidateLocale);
    }
    if (!detectLocale || surface.length < 4) continue;
    const detectorSurface = normalizeMapperSearchText(surface, 'en');
    if (!detectorSurface || !normalized.includes(detectorSurface)) continue;
    if (surface.length > longest) {
      longest = surface.length;
      detected = hintLocale;
      conflict = false;
    } else if (surface.length === longest && detected !== hintLocale) {
      conflict = true;
    }
  }
  const locale = localeByMarket.get(market) ?? (conflict ? null : detected) ?? 'en';
  const primaryRuntime = await runtimeForLocale(locale);
  const primary = primaryRuntime.resolve(query, {
    localeVariant: locale,
    marketScope: market,
    telemetry: NO_TELEMETRY,
  });
  if (market !== 'GLOBAL' || semanticConceptSignature(primary) || carriesAmbiguityGate(primary)) {
    return primary;
  }

  /*
   * A canonical PR may carry an exact mixed-language label while its historical variant still
   * says GLOBAL. In that case the locale detector can be dominated by generic English role words
   * (for example "inclusion") and miss both "arbuz" and "sandía". Consult only locale segments
   * from the exact frozen release that have a concept surface in the query. Accept the fallback
   * only when every resolving locale agrees on the same Search Concept signature. Conflicts and
   * ambiguity gates keep the original unresolved result, so this never manufactures a mapping or
   * a PI identity.
   */
  const consensus = new Map();
  const consensusLocales = [...new Set(localeByMarket.values())]
    .filter((candidateLocale) => conceptCandidateLocales.has(localeKey(candidateLocale)))
    .sort();
  for (const candidateLocale of consensusLocales) {
    if (localeKey(candidateLocale) === localeKey(locale)) continue;
    const runtime = await runtimeForLocale(candidateLocale);
    const candidate = runtime.resolve(query, {
      localeVariant: candidateLocale,
      marketScope: 'GLOBAL',
      telemetry: NO_TELEMETRY,
    });
    const signature = semanticConceptSignature(candidate);
    if (!signature || carriesAmbiguityGate(candidate)) continue;
    const existing = consensus.get(signature);
    const candidateCoverage = candidate.searchMentions.reduce(
      (total, mention) => total + Math.max(0, mention.span.end - mention.span.start),
      0,
    );
    if (!existing || candidateCoverage > existing.coverage) {
      consensus.set(signature, { resolution: candidate, coverage: candidateCoverage });
    }
  }
  return consensus.size === 1 ? [...consensus.values()][0].resolution : primary;
}
`;

writeFileSync(outputPath, source);
console.log(
  `product semantic search edge bundle: ${release.releaseId}, ${releaseBytes.length} source bytes, ${Buffer.byteLength(source)} segmented bundle bytes`,
);
